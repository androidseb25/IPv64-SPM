#!/usr/bin/env python3
"""Generates the API and model references in docs/ from the Swift sources.

One pair of files per client: API_REFERENCE.md / MODELS.md (IPv64) and
NODE64_API_REFERENCE.md / NODE64_MODELS.md (Node64).

Run from the package root after changing the public API:

    python3 Scripts/generate_docs.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources" / "IPv64"
DOCS = ROOT / "docs"

DECL = re.compile(r"^\s*(?:public\s+)?(?:final\s+)?(?:struct|enum|class|extension|protocol|actor)\s+([A-Za-z0-9_.]+)")
ENDPOINT = re.compile(r"`(GET|POST|PUT|PATCH|DELETE) (/[^`]*)`")


def endpoints(doc):
    """All endpoints on the first doc line that names one (a method may serve several)."""
    for line in doc:
        found = list(ENDPOINT.finditer(line))
        if found:
            return found
    return []


def strip_strings(line):
    return re.sub(r'"(?:[^"\\]|\\.)*"', '""', line)


def parse_file(path):
    """Yields (scope, doc_lines, declaration_text) for every public declaration."""
    lines = path.read_text().splitlines()
    stack = []  # (type name or None, depth at which it opened)
    depth = 0
    doc = []
    i = 0
    while i < len(lines):
        raw = lines[i]
        line = raw.strip()
        if line.startswith("///"):
            doc.append(line[3:].strip() if len(line) > 3 else "")
            i += 1
            continue
        if line.startswith("//") or not line:
            if not line.startswith("//"):
                doc = [] if not line else doc
            i += 1
            continue

        scope = stack[-1][0] if stack else ""
        is_attribute = line.startswith("@") and "func" not in line and "var" not in line and "struct" not in line
        if is_attribute:
            i += 1
            continue

        decl_text = line
        if line.startswith(("public func", "public static func", "public init", "public var", "public let",
                            "public static let", "public static var", "case ")):
            # Join multi-line signatures until parentheses balance.
            j = i
            while decl_text.count("(") > decl_text.count(")") and j + 1 < len(lines):
                j += 1
                decl_text += " " + lines[j].strip()
            yield scope, doc, decl_text
            for k in range(i, j):
                depth += strip_strings(lines[k]).count("{") - strip_strings(lines[k]).count("}")
            i = j
            raw = lines[i]

        match = DECL.match(raw)
        code = strip_strings(raw)
        opens, closes = code.count("{"), code.count("}")
        if match and opens > closes:
            name = match.group(1)
            if raw.strip().startswith("extension"):
                stack.append((name, depth))
            else:
                full = f"{scope}.{name}" if scope else name
                yield scope, doc, raw.strip()
                stack.append((full, depth))
            depth += opens - closes
        else:
            depth += opens - closes
            while stack and depth <= stack[-1][1]:
                stack.pop()
        doc = []
        i += 1


def summary(doc):
    text = []
    for line in doc:
        if not line or line.startswith("- ") or line.startswith("`"):
            break
        text.append(line)
    return " ".join(text).replace("``", "`")


def clean_signature(sig):
    sig = sig.split("{")[0].strip() if not sig.rstrip().endswith("async throws {") else sig.rstrip()[:-1].strip()
    sig = re.sub(r"\s+", " ", sig)
    sig = sig.replace("( ", "(").replace(" )", ")").replace(", )", ")")
    return sig.removeprefix("public ")


def api_reference(client):
    accessors = {}  # namespace type -> accessor path
    functions = []
    for path in sorted(client["api"].glob("*.swift")):
        for scope, doc, decl in parse_file(path):
            m = re.match(r"public var (\w+): (\w+) \{ \2\(client: (?:self|client)\) \}", decl)
            if m:
                accessors[f"{scope}.{m.group(2)}"] = (scope, m.group(1), summary(doc))
            elif decl.startswith("public func"):
                functions.append((scope, doc, decl))

    def path_of(namespace):
        parent, name, _ = accessors[namespace]
        return (client["var"] if parent == client["cls"] else path_of(parent)) + "." + name

    by_namespace = {}
    for scope, doc, decl in functions:
        if scope in accessors:
            by_namespace.setdefault(scope, []).append((doc, decl))

    out = [
        f"# {client['cls']} – API reference",
        "",
        "<!-- Generated by Scripts/generate_docs.py – do not edit by hand. -->",
        "",
        f"Every method is `async throws` and throws `{client['error']}`. `{client['var']}` is {client['article']} `{client['cls']}` instance.",
        f"Each entry: Swift call path, HTTP endpoint, signature, summary. Model fields: see `{client['files'][1]}`.",
        "",
        "## Endpoint index",
        "",
        "| Endpoint | Swift |",
        "|---|---|",
    ]
    rows = []
    for namespace, items in by_namespace.items():
        for doc, decl in items:
            name = re.match(r"public func (\w+)", decl).group(1)
            for endpoint in endpoints(doc):
                rows.append((endpoint.group(2), endpoint.group(1), f"`{path_of(namespace)}.{name}`"))
    for path, method, swift in sorted(rows):
        out.append(f"| `{method} {path}` | {swift} |")
    out.append("")

    for namespace in sorted(by_namespace, key=path_of):
        _, _, ns_summary = accessors[namespace]
        out += [f"## `{path_of(namespace)}`", ""]
        if ns_summary:
            out += [ns_summary, ""]
        for doc, decl in by_namespace[namespace]:
            name = re.match(r"public func (\w+)", decl).group(1)
            endpoint = ", ".join(m.group(0) for m in endpoints(doc))
            out.append(f"### `{path_of(namespace)}.{name}` {endpoint}".rstrip())
            out += ["", "```swift", clean_signature(decl), "```", ""]
            text = summary(doc)
            if text:
                out += [text, ""]
    return "\n".join(out)


def models_reference(client):
    types = {}
    order = []
    for path in client["model_sources"]():
        for scope, doc, decl in parse_file(path):
            m = re.match(r"public (?:final class|struct|enum|protocol) (\w+)", decl)
            if m:
                full = f"{scope}.{m.group(1)}" if scope else m.group(1)
                # Endpoint namespaces (`public struct Domains: Sendable { let client: IPv64 }`) are in API_REFERENCE.md.
                if path.parent.name == "API" and re.match(r"public struct \w+: Sendable \{", decl) and full.startswith(client["cls"] + "."):
                    continue
                if full not in types:
                    order.append(full)
                types[full] = {"doc": summary(doc), "decl": decl, "members": [], "file": path}
                continue
            target = types.get(scope)
            if target is None:
                continue
            m = re.match(r"public (?:let|var) (\w+): ([^={]+)", decl)
            if m and m.group(1) == "rawValue" and "IPv64OpenEnum" in target["decl"]:
                continue
            if m and "{" not in decl.split(":", 1)[1].split("=")[0][:0]:
                if re.search(r"\{\s*\w+\(client:", decl):
                    continue
                target["members"].append(f"- `{m.group(1)}: {m.group(2).strip()}` – {summary(doc)}".rstrip(" –"))
                continue
            m = re.match(r"public static let (\w+): Self = \"([^\"]*)\"", decl)
            if m:
                target["members"].append(f"- `.{m.group(1)}` = `\"{m.group(2)}\"`")
                continue
            m = re.match(r"case (\w+)(\(.*?\))?", decl)
            if m and "enum" in target["decl"]:
                target["members"].append(f"- `case {m.group(1)}{m.group(2) or ''}` – {summary(doc)}".rstrip(" –"))

    namespaces = {t for t in order if t.startswith(client["cls"] + ".") and not types[t]["members"]}
    out = [
        f"# {client['cls']} – Models",
        "",
        "<!-- Generated by Scripts/generate_docs.py – do not edit by hand. -->",
        "",
        "Response models are `Codable, Hashable, Sendable` structs with `let` properties.",
        "Most properties are optional because the API spec marks almost nothing as required – unwrap them.",
        "Types conforming to `IPv64OpenEnum` are string-backed structs: compare with the listed constants,",
        "use a `default` branch in `switch`, and create unknown values with `Type(rawValue:)`.",
        "Input types (`…Input`) have a public memberwise `init` with `nil` defaults for optional fields.",
        "",
    ]
    for name in sorted(order, key=str.lower):
        info = types[name]
        if name in namespaces or not info["members"] and "IPv64OpenEnum" not in info["decl"]:
            continue
        kind = "open enum" if "IPv64OpenEnum" in info["decl"] else re.search(r"\b(class|struct|enum|protocol)\b", info["decl"]).group(1)
        out += [f"## `{name}` ({kind})", ""]
        if info["doc"]:
            out += [info["doc"], ""]
        out += info["members"] + [""]
    return "\n".join(out)


CLIENTS = [
    {
        "cls": "IPv64", "var": "ipv64", "error": "IPv64Error", "article": "an",
        "api": SOURCES / "API",
        "model_sources": lambda: [
            *sorted((SOURCES / "Models").rglob("*.swift")), *sorted((SOURCES / "API").glob("*.swift")),
            SOURCES / "IPv64.swift", *sorted((SOURCES / "Core").glob("*.swift")),
        ],
        "files": ("API_REFERENCE.md", "MODELS.md"),
    },
    {
        "cls": "Node64", "var": "node64", "error": "Node64Error", "article": "a",
        "api": SOURCES / "Node64" / "API",
        "model_sources": lambda: [
            *sorted((SOURCES / "Node64" / "Models").rglob("*.swift")), *sorted((SOURCES / "Node64" / "API").glob("*.swift")),
            SOURCES / "Node64" / "Node64.swift", *sorted((SOURCES / "Node64" / "Core").glob("*.swift")),
        ],
        "files": ("NODE64_API_REFERENCE.md", "NODE64_MODELS.md"),
    },
]


def main():
    DOCS.mkdir(exist_ok=True)
    for client in CLIENTS:
        api_file, models_file = client["files"]
        (DOCS / api_file).write_text(api_reference(client))
        (DOCS / models_file).write_text(models_reference(client))
        print(f"Wrote docs/{api_file} and docs/{models_file}")


if __name__ == "__main__":
    main()
